#!/usr/bin/env python3
"""Regenerate bundled character tables using the pinned test environment."""

import importlib.metadata as md
import json
import pathlib
import shutil
import unicodedata as u
import html.entities
from acl_anthology.utils.latex import FAST_LATEX_TABLE
from acl_anthology.text.texmath import TexMath
from acl_anthology.text.stopwords import StopWords
import unidecode

root = pathlib.Path(__file__).resolve().parent.parent
for package, version in [
    ("acl-anthology", "1.3.4"),
    ("pylatexenc", "2.11"),
    ("Unidecode", "1.4.0"),
    ("python-slugify", "9.1.3"),
    ("stop-words", "2018.7.23"),
]:
    assert md.version(package) == version, (package, md.version(package))
    d = md.distribution(package)
    for f in d.files:
        if "LICENSE" in str(f) and package != "acl-anthology":
            shutil.copy(d.locate_file(f), root / "data/licenses" / f"{package}.txt")
TexMath.load_symbols()
StopWords.load()
for name, value in [
    ("latex-encode", {chr(k): v for k, v in FAST_LATEX_TABLE.items()}),
    ("math-symbols", TexMath.cmd_map),
    ("stopwords", sorted(StopWords.stopwords)),
]:
    (root / "data" / f"{name}.json").write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    )
# Preserve all scalar mappings of the exact upstream transliteration backend.
import warnings

with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    mappings = {
        str(i): v
        for i in range(128, 0x110000)
        if not 0xD800 <= i <= 0xDFFF and (v := unidecode.unidecode(chr(i)))
    }
(root / "data/unidecode.json").write_text(
    json.dumps(mappings, ensure_ascii=False, separators=(",", ":")) + "\n"
)
# Keep the original symbol source and its licensing/copyright notice with the derived map.
shutil.copy(
    root / "artifacts/upstream/python/acl_anthology/data/unimathsymbols.txt",
    root / "data/unimathsymbols.txt",
)
s = [
    "// Generated by scripts/generate_tables.py from Python Unicode "
    + u.unidata_version
    + ".",
    "fn unicode_decomposition(c: char) -> Option<&'static str> {",
    "    match c {",
]
for n in range(0x110000):
    c = chr(n)
    d = u.decomposition(c)
    if d and d.split()[0] in ["<compat>", "<wide>", "<narrow>", "<noBreak>"]:
        enc = "".join(
            "\\u{" + format(ord(x), "x") + "}" for x in u.normalize("NFKD", c)
        )
        s.append(f"        '\\u{{{n:x}}}' => Some(\"{enc}\"),")
s += [
    "        _ => None,",
    "    }",
    "}",
    "fn is_nonspacing_mark(c: char) -> bool {",
    "    matches!(c,",
]
ns = [n for n in range(0x110000) if u.category(chr(n)) == "Mn"]
ranges = []
for n in ns:
    if ranges and n == ranges[-1][1] + 1:
        ranges[-1][1] = n
    else:
        ranges.append([n, n])
s += [
    "        "
    + " | ".join(
        f"'\\u{{{a:x}}}'" if a == b else f"'\\u{{{a:x}}}'..='\\u{{{b:x}}}'"
        for a, b in ranges
    ),
    "    )",
    "}",
]
(root / "src/unicode_tables.rs").write_text("\n".join(s) + "\n")

(root / "data/html-entities.json").write_text(
    json.dumps(html.entities.name2codepoint, indent=2) + "\n"
)

# Macro metadata for the native LaTeX parser. Callable rules are implemented in Rust.
from acl_anthology.utils.latex import LW_CONTEXT, L2T_CONTEXT

names = set()
for ctx in [LW_CONTEXT, L2T_CONTEXT]:
    for cat in ctx.category_list:
        names.update(ctx.d[cat]["macros"])
macros = {}
for name in sorted(names):
    w = LW_CONTEXT.get_macro_spec(name)
    t = L2T_CONTEXT.get_macro_spec(name)
    repl = getattr(t, "simplify_repl", None)
    macros[name] = {
        "args": getattr(getattr(w, "args_parser", None), "argspec", "") or "",
        "discard": getattr(t, "discard", True),
        "text": repl if isinstance(repl, (str, type(None))) else None,
        "function": callable(repl),
    }
# `today` is computed from the runtime's local date, never frozen into generated data.
macros["today"]["text"] = None
macros["today"]["function"] = True
(root / "data/latex-macros.json").write_text(
    json.dumps(macros, ensure_ascii=False, indent=2) + "\n"
)

# English names and BCP 47 alias/default-script data used by Paper.language_name.
from langcodes import data_dicts as language_tables, tag_parser
from language_data.name_data import CODE_TO_NAMES

for package, version in [("langcodes", "3.5.1"), ("language-data", "1.4.0")]:
    assert md.version(package) == version
    d = md.distribution(package)
    for f in d.files:
        if "LICENSE" in str(f):
            shutil.copy(d.locate_file(f), root / "data/licenses" / f"{package}.txt")
(root / "data/languages.json").write_text(
    json.dumps(
        {
            "names": {
                k: v.get("en", v.get("und"))
                for k, v in CODE_TO_NAMES.items()
                if v.get("en", v.get("und"))
            },
            "languages": language_tables.LANGUAGE_REPLACEMENTS,
            "territories": language_tables.TERRITORY_REPLACEMENTS,
            "scripts": language_tables.DEFAULT_SCRIPTS,
            "exceptions": sorted(tag_parser.EXCEPTIONS),
        },
        ensure_ascii=False,
        indent=2,
    )
    + "\n"
)

from pylatexenc.latex2text._defaultspecs import fmt_math_text_style

styles = {
    "mathbb": "doublestruck",
    "mathbf": "bold",
    "mathcal": "script",
    "mathfrak": "fraktur",
    "mathit": "italic",
    "mathscr": "script",
    "mathsf": "sans",
    "mathtt": "monospace",
}
(root / "data/math-fonts.json").write_text(
    json.dumps(
        {
            name: {
                chr(c): fmt_math_text_style(chr(c), style)
                for c in range(128)
                if fmt_math_text_style(chr(c), style) != chr(c)
            }
            for name, style in styles.items()
        },
        ensure_ascii=False,
        indent=2,
    )
    + "\n"
)
